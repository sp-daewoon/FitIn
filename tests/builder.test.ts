const item = (machine: MachineId, extra: Partial<PlanItem> = {}): PlanItem => ({
  machine,
  sets: 3,
  work: 60,
  rest: 90,
  ...extra,
});

test('added movements persist in order, and a movement the user repeats is allowed', () => {
  const template = [...defaultPlan('fullA'), item('deadlift'), item('facePull'), item('crunch')];
  validateTemplate(template);
  const preferences = { ...defaultPreferences, templates: { fullA: template } };
  const stored = resolveTemplate('fullA', preferences);
  assert.deepEqual(
    stored.slice(-3).map((x) => x.machine),
    ['deadlift', 'facePull', 'crunch'],
  );
  // The user can deliberately run the same movement twice in one session.
  validateTemplate([...defaultPlan('fullA'), item('legPress')]);
  assert.throws(() => validateTemplate(Array.from({ length: 13 }, () => item('squat'))));
  // Nothing generated by the app produces a repeat on its own.
  for (const routine of Object.keys(routineNames) as (keyof typeof routineNames)[]) {
    const generated = defaultPlan(routine).map((x) => x.machine);
    assert.equal(
      new Set(generated).size,
      generated.length,
      `${routine} default repeats a movement`,
    );
  }
});

test('a repeated movement keeps distinct phases, so its sets are recorded separately', () => {
  const plan = [item('legPress', { sets: 1 }), item('legPress', { sets: 1 })];
  const phases = buildPhases(plan);
  const ids = phases.map((x) => x.id);
  assert.equal(new Set(ids).size, ids.length);
  let session = begin('fullA', plan, 0);
  const first = position(session, 11000).phase!;
  assert.equal(first.kind, 'work');
  session = applyCommand(session, {
    id: 'c1',
    sessionId: session.id,
    phaseId: first.id,
    revision: 0,
    source: 'app',
    type: 'next',
    at: 11000,
  });
  assert.deepEqual(session.confirmed, [first.id]);
  const second = position(session, 80000).phase!;
  assert.equal(second.kind, 'work');
  assert.notEqual(second.id, first.id);
  assert.equal(second.machine, 'legPress');
});

test('global rest reaches every set except an explicitly overridden exercise', () => {
  const plan = [item('legPress'), item('deadlift', { rest: 150, restOverride: true })];
  const applied = applyGlobalRest(plan, 120);
  assert.equal(applied[0].rest, 120);
  assert.equal(applied[1].rest, 150);
  assert.equal(plan[0].rest, 90, 'input is not mutated');
  const fresh = resolveTemplate('fullA', { ...defaultPreferences, globalRest: 120 });
  assert.ok(fresh.every((x) => x.rest === 120));
  assert.equal(defaultPreferences.globalRest, DEFAULT_REST);
});

test('per-exercise work duration changes only that exercise time', () => {
  const before = [item('legPress'), item('deadlift')];
  const after = [item('legPress'), item('deadlift', { work: 90 })];
  const a = planBreakdown(before),
    b = planBreakdown(after);
  assert.equal(b.work - a.work, 90);
  assert.equal(a.rest, b.rest);
  assert.equal(a.move, b.move);
  assert.equal(a.move, 60);
  assert.equal(a.setup + a.work + a.rest + a.move, planSeconds(before));
});

test('a plan longer than forty minutes runs to its end instead of being truncated', () => {
  const long = [
    ...defaultPlan('fullA'),
    item('deadlift', { sets: 4, work: 90, rest: 150 }),
    item('barbellRow', { sets: 4, work: 90, rest: 150 }),
  ];
  const total = planSeconds(long);
  assert.ok(total > TOTAL_SECONDS, 'the fixture is deliberately past the old cap');
  validateTemplate(long);
  validatePlan(long);

  const session = begin('fullA', long, 0);
  assert.equal(session.timeLimit, null, 'a new session carries no time limit');
  assert.equal(
    session.phases.reduce((n, x) => n + x.seconds, 0),
    total,
    'every planned second reaches the session; nothing is dropped',
  );
  assert.deepEqual(
    [...new Set(session.phases.filter((x) => x.kind === 'work').map((x) => x.machine))],
    [...new Set(long.map((x) => x.machine))],
    'every movement including both finishers is present',
  );

  // Forty minutes is a default planning figure, not a cutoff: the session is still running there.
  const atOldCap = position(session, TOTAL_SECONDS * 1000);
  assert.ok(atOldCap.phase, 'the session does not end at forty minutes');
  // The final finisher is reachable, and the session ends only when the plan ends.
  assert.equal(position(session, (total - 1) * 1000).phase?.machine, 'barbellRow');
  assert.equal(position(session, (total + 1) * 1000).phase, null);

  // A migrated session keeps the cap it was created under.
  const migrated = { ...session, timeLimit: TOTAL_SECONDS };
  assert.equal(position(migrated, (total - 1) * 1000).phase, null);
});

test('a starter substitutes one movement, never appends, and names what it replaced', () => {
  const template = [...defaultPlan('upper'), item('deadlift')];
  const proposal = withStarters(template, ['shoulderPress']);
  assert.equal(proposal.items[0].machine, 'shoulderPress', 'the starter leads the session');
  assert.equal(proposal.items.length, template.length, 'substitution never grows the session');
  assert.equal(proposal.replaced.length, 1);
  assert.ok(
    !proposal.items.some((x) => x.machine === proposal.replaced[0]),
    'the replaced movement is actually gone, and the caller is told which one',
  );
  // Since a movement the user appended is no longer distinguishable from a generated one, it can
  // be the movement chosen for substitution. That is reported, never silent.
  assert.equal(planSeconds(proposal.items), planSeconds(template), 'timing is unchanged');
});

test('a saved template survives a storage roundtrip and a version-2 snapshot still opens', () => {
  const template = [...defaultPlan('fullA'), item('deadlift', { work: 90 })];
  const saved = {
    ...emptyData,
    preferences: { ...defaultPreferences, globalRest: 120, templates: { fullA: template } },
  };
  const back = decode(JSON.stringify(saved));
  assert.equal(back.version, 4);
  assert.equal(back.preferences.globalRest, 120);
  assert.deepEqual(back.preferences.templates.fullA, template);

  const legacy = {
    version: 2,
    history: [],
    session: null,
    sound: true,
    preferences: {
      level: 'beginner',
      split: 'fixed',
      starters: [],
      savedPlan: [{ machine: 'squat', sets: 2, work: 60, rest: 120 }],
    },
  };
  const upgraded = decode(JSON.stringify(legacy));
  assert.equal(upgraded.version, 4);
  assert.equal(upgraded.preferences.globalRest, DEFAULT_REST);
  assert.deepEqual(upgraded.preferences.templates, {});
  assert.equal(upgraded.preferences.savedPlan![0].rest, 120, 'explicit version-2 rest is kept');
  assert.equal(resolveTemplate('fullB', upgraded.preferences)[0].rest, 120);

  assert.throws(() =>
    decode(
      JSON.stringify({
        ...saved,
        preferences: { ...saved.preferences, globalRest: 20 },
      }),
    ),
  );
  assert.throws(() =>
    decode(
      JSON.stringify({
        ...saved,
        preferences: { ...saved.preferences, templates: { nope: template } },
      }),
    ),
  );
});

test('in-session reorder targets the first upcoming block and leaves the current one alone', async () => {
  const { swapUpcoming } = await import('../src/workout');
  const plan = [
    item('legPress', { sets: 1 }),
    item('chestPress', { sets: 1 }),
    item('latPulldown', { sets: 1 }),
    item('chestPress', { sets: 1 }),
  ];
  const session = begin('fullA', plan, 0);
  const swapped = swapUpcoming(session, 'chestPress', 'latPulldown', 5000);
  const order = swapped.phases.filter((x) => x.kind === 'work').map((x) => x.machine);
  assert.deepEqual(order, ['legPress', 'latPulldown', 'chestPress', 'chestPress']);
  // The block already started or finished is not reordered.
  assert.equal(swapUpcoming(session, 'legPress', 'chestPress', 5000), session);
  assert.equal(swapUpcoming(session, 'chestPress', 'chestPress', 5000), session);
});

test('a hand-edited rest value is kept as a labeled override, not overwritten by global rest', () => {
  const edited = [item('legPress'), item('deadlift', { rest: 120 }), item('crunch', { rest: 90 })];
  const marked = markRestOverrides(edited, 90);
  assert.deepEqual(
    marked.map((x) => !!x.restOverride),
    [false, true, false],
  );
  // The global control still reaches the untouched items and leaves the explicit one alone.
  const after = applyGlobalRest(marked, 60);
  assert.deepEqual(
    after.map((x) => x.rest),
    [60, 120, 60],
  );
  assert.equal(edited[1].restOverride, undefined, 'input is not mutated');
  // An item already overridden keeps its flag, and a matching value is not falsely marked.
  assert.equal(
    markRestOverrides([item('squat', { rest: 90, restOverride: true })], 90)[0].restOverride,
    true,
  );
});

test('a custom cycle is the user’s own visit order and drives what the planner shows', async () => {
  const { MAX_CUSTOM_VISITS, nextRoutine, routineCycle } = await import('../src/workout');

  assert.deepEqual(routineCycle('custom', ['upper', 'lower', 'legs']), ['upper', 'lower', 'legs']);
  assert.deepEqual(routineCycle('custom', ['push']), ['push'], 'a one-visit cycle is allowed');
  // The planner renders one card per visit, so the cycle length is what decides whether
  // 다다음 방문 exists at all.
  assert.equal(routineCycle('custom', ['upper', 'lower']).length, 2);
  assert.equal(routineCycle('upperLower').length, 2);
  assert.equal(routineCycle('ppl').length, 3);
  assert.equal(routineCycle('fixed').length, 1);

  assert.equal(
    routineCycle('custom', ['upper', 'lower', 'legs', 'push']).length,
    MAX_CUSTOM_VISITS,
    'more visits than the planner can show are not stored silently as a longer cycle',
  );
  // Nothing is invented when the user has not defined a cycle yet.
  assert.deepEqual(routineCycle('custom'), ['fullA']);
  assert.deepEqual(routineCycle('custom', []), ['fullA']);

  // Progression follows the custom order, not the built-in splits.
  const done = (routine: 'upper' | 'lower' | 'legs') => ({
    id: routine,
    routine,
    endedAt: 1,
    elapsed: 600,
    confirmedSets: 6,
    completed: true,
    reason: 'routine' as const,
    performed: ['legPress' as const],
  });
  const custom = ['upper', 'lower', 'legs'] as const;
  assert.equal(nextRoutine([], 'custom', [...custom]), 'upper');
  assert.equal(nextRoutine([done('upper')], 'custom', [...custom]), 'lower');
  assert.equal(nextRoutine([done('legs')], 'custom', [...custom]), 'upper', 'the cycle wraps');
});

test('a stored custom cycle roundtrips and an invalid one is rejected', () => {
  const saved = {
    ...emptyData,
    preferences: {
      ...defaultPreferences,
      split: 'custom' as const,
      customCycle: ['upper', 'legs'],
    },
  };
  assert.deepEqual(decode(JSON.stringify(saved)).preferences.customCycle, ['upper', 'legs']);
  // Absent is valid: every other split ignores the field.
  assert.equal(decode(JSON.stringify(emptyData)).preferences.customCycle, undefined);
  for (const bad of [[], ['upper', 'lower', 'legs', 'push'], ['nope'], 'upper']) {
    assert.throws(
      () =>
        decode(
          JSON.stringify({ ...saved, preferences: { ...saved.preferences, customCycle: bad } }),
        ),
      `accepted ${JSON.stringify(bad)}`,
    );
  }
});
